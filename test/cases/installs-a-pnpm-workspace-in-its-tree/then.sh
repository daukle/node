set -eu

fail() {
  echo "$1" >&2
  exit 1
}

modules=packages/b/build/daukle/node_modules
[ -e "$modules/a/index.js" ] || fail "$modules/a does not resolve to packages/a"
: > packages/a/.probe
shown=0
[ -e "$modules/a/.probe" ] && shown=1
rm -f packages/a/.probe
[ "$shown" -eq 1 ] || fail "$modules/a is a copy of packages/a, not a link to it"

for placed in package.json pnpm-workspace.yaml pnpm-lock.yaml packages/a/package.json packages/b/package.json; do
  grep -q 'generated by daukle/node from daukle.toml' "$placed" || fail "$placed is not a marked copy"
done

listed=$(git status --porcelain --untracked-files=all | sed 's/^...//' |
  grep -v -e '^build/' -e '/build/' -e '^plugins/' -e '^fixtures/' | sort)
expected=$(printf '%s\n' daukle.toml daukle/pnpm/lock.lua packages/a/index.js packages/b/index.js \
  stderr.txt stdout.txt then.txt | sort)
[ "$listed" = "$expected" ] || fail "git status lists more than the case's own files: $listed"
