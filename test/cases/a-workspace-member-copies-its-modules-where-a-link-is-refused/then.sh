set -eu

fail() {
  echo "$1" >&2
  exit 1
}

for placed in package.json pnpm-workspace.yaml pnpm-lock.yaml packages/a/package.json packages/b/package.json; do
  grep -q 'generated by daukle/node from daukle.toml' "$placed" || fail "$placed was not placed by the root's install"
done
[ -e build/daukle/node_modules/.modules.yaml ] || fail "the root's install did not run in the project's tree"
for member in . packages/a packages/b; do
  [ -f "$member/node_modules/.daukle-copy" ] || fail "$member/node_modules is not a copy"
done
[ -f packages/b/node_modules/semver/package.json ] || fail "the member's copy was made before the install and never refreshed"
