  MARKER_KEY = json_string(MARKER_KEY),
  MARKER_TEXT = json_string(MARKER_TEXT),
  PLACED_NAME = json_string(PLACED_NAME),
  COPY_MARKER = json_string(COPY_MARKER),
  NESTED_NAME = json_string(NESTED_NAME),
  PLACED_NESTED_NAME = json_string(PLACED_NESTED_NAME),
