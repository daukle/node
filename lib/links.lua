local SCRIPT_NAME = "__daukle_link__.mjs"
local PLACED_NAME = "__daukle_placed__.json"
local MARKER_KEY = "//"
local MARKER_TEXT = "generated by daukle/node from daukle.toml: edit that, this file is replaced"
                    .. " by every node:install"
local COPY_MARKER = ".daukle-copy"
local NESTED_NAME = "__daukle_nested__.json"
local PLACED_NESTED_NAME = "__daukle_placed_nested__.json"
local WORKSPACE_NAME = "__daukle_workspace__.json"
local PLACED_FILES_NAME = "__daukle_placed_files__.json"
local WORKSPACE_FILE_NAME = "__daukle_pnpm_workspace__.yaml"
local TEXT_MARKER = "# " .. MARKER_TEXT

--- Where pnpm installs each workspace project's modules, relative to that project's directory.
local WORKSPACE_MODULES_DIR = "build/daukle/node_modules"

--[[ @implNote package.json is placed as a copy and never linked, because core
     writes a generated file by atomic rename: a symlink would turn an edit of
     the root file into an edit of the generated one that the next sync silently
     overwrites, and a hard link goes stale on the first sync that changes it.
     The bytes placed are kept beside the generated file, so a root copy that is
     merely an older generation is told apart from a hand edit. A junction is
     used on Windows because it needs no privilege, and lstat reports one as a
     symbolic link whose readlink can carry a "\\?\" prefix. ]]
local TEMPLATE = [==[
import { cpSync, existsSync, lstatSync, mkdirSync, readFileSync, readlinkSync, realpathSync, rmSync,
  symlinkSync, writeFileSync } from "node:fs";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";

const MARKER_KEY = __DAUKLE_MARKER_KEY__;
const MARKER_TEXT = __DAUKLE_MARKER_TEXT__;
const PLACED_NAME = __DAUKLE_PLACED_NAME__;
const COPY_MARKER = __DAUKLE_COPY_MARKER__;
const NESTED_NAME = __DAUKLE_NESTED_NAME__;
const PLACED_NESTED_NAME = __DAUKLE_PLACED_NESTED_NAME__;
const WORKSPACE_NAME = __DAUKLE_WORKSPACE_NAME__;
const PLACED_FILES_NAME = __DAUKLE_PLACED_FILES_NAME__;
const TEXT_MARKER = __DAUKLE_TEXT_MARKER__;
const LINK_REFUSALS = new Set(["EPERM", "ENOTSUP", "EOPNOTSUPP", "EINVAL"]);

const windows = process.platform === "win32";
const derived = resolve(".");
const projectRoot = resolve(derived, "..", "..", "..");
const packageRoot = resolve(process.argv[2] ?? projectRoot);
const placesOnly = process.argv[3] === "place";
const derivedModules = join(derived, "node_modules");
const derivedManifest = join(derived, "package.json");
const placedRecord = join(derived, PLACED_NAME);
const rootModules = join(packageRoot, "node_modules");
const rootManifest = join(packageRoot, "package.json");

class Refusal extends Error {}

function withoutDevicePrefix(path) {
  return path.replace(/^\\\\\?\\|^\\\?\?\\/, "");
}

function comparable(path) {
  const plain = resolve(path);
  return windows ? plain.toLowerCase() : plain;
}

function shown(path) {
  const fromProject = relative(projectRoot, path);
  if (fromProject.startsWith("..") || isAbsolute(fromProject)) return path.split(sep).join("/");
  return fromProject.split(sep).join("/");
}

function entryAt(path) {
  try {
    return lstatSync(path);
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
}

function modulesAction() {
  const entry = entryAt(rootModules);
  if (entry === null) return "place";
  if (entry.isSymbolicLink()) {
    const target = resolve(dirname(rootModules), withoutDevicePrefix(readlinkSync(rootModules)));
    if (comparable(target) === comparable(derivedModules)) return existsSync(rootModules) ? "keep" : "replace-link";
    const shared = /(^|\/)build\/daukle\/[^/]+\/node_modules$/.test(target.split(sep).join("/"))
      ? ": two node toolchains cannot share one package root" : "";
    throw new Refusal(`"${shown(rootModules)}" links to "${shown(target)}", not to this`
      + ` toolchain's "${shown(derivedModules)}"${shared}`);
  }
  if (entry.isDirectory() && existsSync(join(rootModules, COPY_MARKER))) return "replace-copy";
  throw new Refusal(`"${shown(rootModules)}" is not one daukle placed: remove it, the packages are`
    + ` installed into "${shown(derivedModules)}"`);
}

function carriesTheMarker(bytes) {
  try {
    const manifest = JSON.parse(bytes.toString("utf8"));
    if (manifest === null || typeof manifest !== "object" || Array.isArray(manifest)) return false;
    return Object.keys(manifest)[0] === MARKER_KEY && manifest[MARKER_KEY] === MARKER_TEXT;
  } catch {
    return false;
  }
}

function manifestAction() {
  const entry = entryAt(rootManifest);
  if (entry === null) return "place";
  const present = entry.isFile() ? readFileSync(rootManifest) : null;
  if (present === null || !carriesTheMarker(present)) {
    throw new Refusal(`"${shown(rootManifest)}" is not one daukle placed: daukle generates it from`
      + " daukle.toml, so remove it (daukle migrate moves it aside)");
  }
  if (!existsSync(placedRecord)) return "place";
  if (present.equals(readFileSync(placedRecord))) return "place";
  throw new Refusal(`"${shown(rootManifest)}" was edited, and node:install replaces it: move the`
    + " change into daukle.toml");
}

function jsonAt(path) {
  return existsSync(path) ? JSON.parse(readFileSync(path, "utf8")) : {};
}

const placements = jsonAt(join(derived, NESTED_NAME));
const placedNestedRecord = join(derived, PLACED_NESTED_NAME);
const placedNested = jsonAt(placedNestedRecord);

function isInside(parent, path) {
  const fromParent = relative(comparable(parent), comparable(path));
  return fromParent === "" || (!fromParent.startsWith("..") && !isAbsolute(fromParent));
}

/** @implNote the directory is resolved through its links, so a linked directory cannot carry a write outside the package. */
function nestedTarget(directory) {
  const folder = join(packageRoot, directory);
  const entry = entryAt(folder);
  if (entry === null || !entry.isDirectory() || !isInside(realpathSync(packageRoot), realpathSync(folder))) {
    throw new Refusal(`"${shown(folder)}" is not a directory of the package, and daukle.toml's`
      + " nestedPackages places a package.json in it");
  }
  return join(folder, "package.json");
}

function nestedActions() {
  return Object.entries(placements).map(([directory, text]) => {
    const target = nestedTarget(directory);
    const entry = entryAt(target);
    if (entry !== null) {
      const present = entry.isFile() ? readFileSync(target) : null;
      if (present === null || !carriesTheMarker(present)) {
        throw new Refusal(`"${shown(target)}" is not one daukle placed: daukle generates it from`
          + " daukle.toml's nestedPackages, so remove it (daukle migrate moves it aside)");
      }
      if (placedNested[directory] !== undefined && present.toString("utf8") !== placedNested[directory]) {
        throw new Refusal(`"${shown(target)}" was edited, and node:install replaces it: move the`
          + " change into daukle.toml");
      }
    }
    return { directory, target, text };
  });
}

/** Removes a placement daukle.toml no longer names, only while it is still exactly what was placed. */
function pruneDroppedPlacements() {
  for (const [directory, text] of Object.entries(placedNested)) {
    if (placements[directory] !== undefined) continue;
    const target = join(packageRoot, directory, "package.json");
    const entry = entryAt(target);
    if (entry !== null && entry.isFile() && readFileSync(target, "utf8") === text) rmSync(target);
  }
}

function placeNested(actions) {
  pruneDroppedPlacements();
  const record = {};
  for (const action of actions) {
    writeFileSync(action.target, action.text);
    record[action.directory] = action.text;
  }
  writeFileSync(placedNestedRecord, JSON.stringify(record));
}

const workspace = jsonAt(join(derived, WORKSPACE_NAME));
const workspaceFiles = workspace.files ?? {};
const placedFilesRecord = join(derived, PLACED_FILES_NAME);
const placedFiles = jsonAt(placedFilesRecord);

function fileActions() {
  return Object.entries(workspaceFiles).map(([name, source]) => {
    const target = join(packageRoot, name);
    const entry = entryAt(target);
    if (entry !== null) {
      const present = entry.isFile() ? readFileSync(target, "utf8") : null;
      if (present === null || present.split(/\r?\n/, 1)[0] !== TEXT_MARKER) {
        throw new Refusal(`"${shown(target)}" is not one daukle placed: daukle generates it from`
          + " daukle.toml, so remove it (daukle migrate moves it aside)");
      }
      if (placedFiles[name] !== undefined && present !== placedFiles[name]) {
        throw new Refusal(`"${shown(target)}" was edited, and node:install replaces it: move the`
          + " change into daukle.toml");
      }
    }
    return { name, target, text: TEXT_MARKER + "\n" + readFileSync(join(derived, source), "utf8") };
  });
}

/** Places each workspace file, after removing one daukle.toml no longer names while it is still exactly what was placed. */
function placeFiles(actions) {
  for (const [name, text] of Object.entries(placedFiles)) {
    if (workspaceFiles[name] !== undefined) continue;
    const target = join(packageRoot, name);
    const entry = entryAt(target);
    if (entry !== null && entry.isFile() && readFileSync(target, "utf8") === text) rmSync(target);
  }
  const record = {};
  for (const action of actions) {
    writeFileSync(action.target, action.text);
    record[action.name] = action.text;
  }
  writeFileSync(placedFilesRecord, JSON.stringify(record));
}

function workspaceModules() {
  return workspace.modules === undefined ? null : resolve(packageRoot, workspace.modules);
}

/** @implNote pnpm installs a workspace project's modules into that project's own directory, so the derived node_modules is a link to them. */
function linkDerivedModules(target) {
  mkdirSync(target, { recursive: true });
  const entry = entryAt(derivedModules);
  if (entry !== null && entry.isSymbolicLink()) {
    const present = resolve(dirname(derivedModules), withoutDevicePrefix(readlinkSync(derivedModules)));
    if (comparable(present) === comparable(target)) return;
    rmSync(derivedModules, { force: true });
  } else if (entry !== null) {
    rmSync(derivedModules, { recursive: true, force: true });
  }
  if (windows) symlinkSync(target, derivedModules, "junction");
  else symlinkSync(relative(derived, target), derivedModules, "dir");
}

function copyModules() {
  cpSync(derivedModules, rootModules, { recursive: true, verbatimSymlinks: true });
  writeFileSync(join(rootModules, COPY_MARKER), "");
}

function linkModules() {
  if (process.env.DAUKLE_NODE_LINK === "copy") return copyModules();
  try {
    if (windows) symlinkSync(derivedModules, rootModules, "junction");
    else symlinkSync(relative(packageRoot, derivedModules), rootModules, "dir");
  } catch (error) {
    if (!LINK_REFUSALS.has(error.code)) throw error;
    copyModules();
  }
}

/** @implNote npm creates no node_modules when nothing is declared, and the root entry needs one to resolve to or copy from. */
function placeModules(action) {
  mkdirSync(derivedModules, { recursive: true });
  if (action === "keep") return;
  if (action === "replace-link") rmSync(rootModules, { force: true });
  if (action === "replace-copy") rmSync(rootModules, { recursive: true, force: true });
  linkModules();
}

function placeManifest() {
  const bytes = readFileSync(derivedManifest);
  rmSync(rootManifest, { force: true });
  writeFileSync(rootManifest, bytes);
  writeFileSync(placedRecord, bytes);
}

/** @implNote a worktree's `.git` is a file naming its own git directory, whose `commondir` names the shared one, and git reads `info/exclude` from the shared one alone. */
function sharedGitDirectory(dotGit, entry) {
  if (entry.isDirectory()) return dotGit;
  if (!entry.isFile()) return null;
  const pointer = /^gitdir:[ \t]*(.+?)[ \t]*$/m.exec(readFileSync(dotGit, "utf8"));
  if (pointer === null) return null;
  const gitDirectory = resolve(dirname(dotGit), pointer[1]);
  const commonFile = join(gitDirectory, "commondir");
  if (!existsSync(commonFile)) return gitDirectory;
  return resolve(gitDirectory, readFileSync(commonFile, "utf8").trim());
}

function enclosingRepository() {
  for (let directory = packageRoot; ; directory = dirname(directory)) {
    const dotGit = join(directory, ".git");
    const entry = entryAt(dotGit);
    if (entry !== null) {
      const gitDirectory = sharedGitDirectory(dotGit, entry);
      return gitDirectory === null ? null : { root: directory, gitDirectory };
    }
    if (dirname(directory) === directory) return null;
  }
}

/** @implNote no pattern ends in a slash: git classifies a POSIX symlink as a file, so a directory-only pattern would not exclude the link. */
function excludePattern(repositoryRoot, path) {
  return "/" + relative(repositoryRoot, path).split(sep).join("/").replace(/[\\*?[\]]/g, "\\$&");
}

/** Keeps the placed entries out of git through the clone's own `info/exclude`, so no project file is edited; outside a git repository there is nothing to keep them out of. */
function excludeFromRepository(placedTargets) {
  const repository = enclosingRepository();
  if (repository === null) return;
  const excludeFile = join(repository.gitDirectory, "info", "exclude");
  const present = existsSync(excludeFile) ? readFileSync(excludeFile, "utf8") : "";
  const lines = new Set(present.split(/\r?\n/));
  const missing = [rootModules, rootManifest, ...placedTargets].map((path) => excludePattern(repository.root, path))
    .filter((pattern) => !lines.has(pattern));
  if (missing.length === 0) return;
  const separator = present === "" || present.endsWith("\n") ? "" : "\n";
  mkdirSync(dirname(excludeFile), { recursive: true });
  writeFileSync(excludeFile, present + separator + missing.join("\n") + "\n");
}

let modules;
let nested;
let files;
try {
  modules = placesOnly ? null : modulesAction();
  manifestAction();
  nested = nestedActions();
  files = fileActions();
} catch (error) {
  if (!(error instanceof Refusal)) throw error;
  console.error(error.message);
  process.exit(1);
}
const installed = workspaceModules();
if (!placesOnly) {
  if (installed !== null) linkDerivedModules(installed);
  placeModules(modules);
}
placeManifest();
placeNested(nested);
placeFiles(files);
excludeFromRepository([...nested, ...files].map((action) => action.target).concat(installed === null ? [] : [installed]));
